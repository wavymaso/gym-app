#!/bin/bash
# Runs the coaching engine on your data (a copy of the Mac app's database) and writes BACKTEST.md:
# trend forecasts (current vs engine), energy density vs the fitted 5 500 baseline, and a weekly
# replay of check-in decisions as if the engine had been live. ~1 minute.
set -e
cd "$(dirname "$0")/.."
D=~/Library/Containers/com.wavymaso.gym/Data/Library/Application\ Support
M=$(mktemp -d); trap 'rm -rf "$M"' EXIT
cp -p "$D"/default.store* "$M/"
MF="$PWD/.backups/backtest/mf-expenditure.csv"
{
  echo "# Engine backtest ($(date +%Y-%m-%d))"; echo
  echo "Generated by \`tools/engine.sh\` on a copy of your data. Train = first two thirds of the history, test = the last third."; echo
  echo "## Trend forecasts and energy density"; echo; echo '```'
  TREND=1 Tests/backtest/run.sh "$M/default.store" "$MF" 2>&1 | grep -v "^data:\|tuned\|jump99\|best err"
  echo '```'; echo
} > BACKTEST.md
REPLAY=1 REPORT="$M/replay.md" Tests/backtest/run.sh "$M/default.store" "$MF" >/dev/null 2>&1 || true
cat "$M/replay.md" >> BACKTEST.md
echo "wrote BACKTEST.md"
